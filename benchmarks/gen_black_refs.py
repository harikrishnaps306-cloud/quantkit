"""Generates tests/black_accuracy.rs from 150-digit mpmath references.

Every reference value is computed independently of the Rust code with
arbitrary-precision arithmetic from the defining formula
    b(x, s) = e^{x/2} Phi(x/s + s/2) - e^{-x/2} Phi(x/s - s/2).
"""
import os
import sys

from mpmath import erfc, exp, log, mp, mpf, sqrt

mp.dps = 150
OUT = sys.argv[1]

XS = [-1e-12, -1e-6, -1e-3, -0.05, -0.5, -2.0, -10.0, -50.0, -300.0, -2000.0]
SS = [1e-9, 1e-6, 1e-3, 0.02, 0.2, 1.0, 1.9, 2.1, 5.0, 40.0, 3000.0]


def cdf(z):
    return erfc(-z / sqrt(2)) / 2


def b(x, s):
    x, s = mpf(x), mpf(s)
    d1 = x / s + s / 2
    d2 = d1 - s
    return exp(x / 2) * cdf(d1) - exp(-x / 2) * cdf(d2)


rows = []
for x in XS:
    for s in SS:
        ref = b(x, s)
        if ref <= 0:
            continue
        ln_ref = float(log(ref))
        rows.append((x, s, ln_ref))

lines = []
lines.append("//! GENERATED by benchmarks/gen_black_refs.py from 150-digit mpmath arithmetic.")
lines.append("//! Do not edit by hand. Each entry is (x, s, ln b(x, s)) for the defining formula")
lines.append("//! b(x, s) = e^{x/2} Phi(x/s + s/2) - e^{-x/2} Phi(x/s - s/2), computed")
lines.append("//! independently of the code under test.")
lines.append("")
lines.append("use quantkit::black::{ln_normalised_otm, normalised_otm};")
lines.append("")
lines.append("const REFS: &[(f64, f64, f64)] = &[")
for x, s, l in rows:
    lines.append(f"    ({x!r}, {s!r}, {l!r}),")
lines.append("];")
lines.append(
    """
/// The conditioning of the problem: x and s are rounded f64 values, and
/// ln b moves by about (x/s)^2 per unit relative change of either, so no
/// double-precision implementation can beat eps * (1 + (x/s)^2) in general.
fn allowed(x: f64, s: f64) -> f64 {
    let h2 = (x / s) * (x / s);
    8.0 * f64::EPSILON * (1.0 + h2) + 3e-14
}

#[test]
fn ln_b_matches_150_digit_arithmetic_across_the_domain() {
    let mut worst = 0.0_f64;
    for &(x, s, ln_ref) in REFS {
        let got = ln_normalised_otm(x, s);
        let err = (got - ln_ref).abs();
        let limit = allowed(x, s);
        worst = worst.max(err / limit);
        assert!(
            err <= limit,
            "x={x:e} s={s:e}: ln b = {got} vs reference {ln_ref} (err {err:e}, allowed {limit:e})"
        );
    }
    // Sanity: the grid is large and the tolerance is not trivially loose.
    assert!(REFS.len() > 80);
    println!("worst error / allowed = {worst:.3}");
}

#[test]
fn b_itself_is_accurate_where_it_is_representable() {
    let mut checked = 0;
    for &(x, s, ln_ref) in REFS {
        if ln_ref > -700.0 {
            let got = normalised_otm(x, s);
            let rel = (got.ln() - ln_ref).abs();
            assert!(rel <= allowed(x, s), "x={x:e} s={s:e}: {got:e} vs e^{ln_ref}");
            checked += 1;
        }
    }
    assert!(checked > 40);
}
"""
)
# ---- implied-volatility references -------------------------------------------
import math

IV_ROWS = []
S0, R, Q = 100.0, 0.01, 0.02
for T in (1.0, 0.05, 0.003):
    for VOL in (0.05, 0.2, 0.8):
        s = VOL * math.sqrt(T)
        F = S0 * math.exp((R - Q) * T)
        for d in (0.0, 1.0, 3.0, 10.0, 20.0, 30.0, 36.0):
            for is_call in (True, False):
                x_abs = s * (d + s / 2)
                K = F * math.exp(x_abs) if is_call else F * math.exp(-x_abs)
                if not (1e-8 <= K <= 1e12):
                    continue  # outside the supported input domain
                Sm, Km, Rm, Qm, Vm, Tm = map(mpf, (S0, K, R, Q, VOL, T))
                sq = Vm * sqrt(Tm)
                d1 = (log(Sm / Km) + (Rm - Qm + Vm * Vm / 2) * Tm) / sq
                d2 = d1 - sq
                if is_call:
                    p = Sm * exp(-Qm * Tm) * cdf(d1) - Km * exp(-Rm * Tm) * cdf(d2)
                else:
                    p = Km * exp(-Rm * Tm) * cdf(-d2) - Sm * exp(-Qm * Tm) * cdf(-d1)
                if p < mpf("1e-290"):
                    continue
                IV_ROWS.append((S0, K, R, Q, VOL, T, is_call, float(p)))

lines.append("")
lines.append(
    "/// (spot, strike, rate, dividend yield, true vol, expiry, is_call, price from 150-digit arithmetic)"
)
lines.append("type IvRef = (f64, f64, f64, f64, f64, f64, bool, f64);")
lines.append("const IV_REFS: &[IvRef] = &[")
for r in IV_ROWS:
    lines.append(
        "    ("
        + ", ".join(str(v).lower() if isinstance(v, bool) else repr(v) for v in r)
        + "),"
    )
lines.append("];")
lines.append(
    """
#[test]
fn implied_vol_recovers_the_true_volatility_deep_into_the_tails() {
    use quantkit::implied_vol::{solve_detailed, SolverConfig};
    use quantkit::{OptionParams, OptionType};
    let mut worst = 0.0_f64;
    for &(s, k, r, q, vol, t, is_call, price) in IV_REFS {
        let kind = if is_call { OptionType::Call } else { OptionType::Put };
        let c = OptionParams::builder()
            .spot(s).strike(k).rate(r).dividend_yield(q).expiry(t)
            .build_contract()
            .unwrap();
        let sol = solve_detailed(&c, kind, price, SolverConfig::default())
            .unwrap_or_else(|e| panic!("s={s} k={k} vol={vol} t={t} call={is_call} price={price:e}: {e}"));
        let rel = (sol.vol - vol).abs() / vol;
        worst = worst.max(rel);
        assert!(rel < 2e-12, "k={k} vol={vol} t={t} call={is_call} price={price:e}: got {} (rel err {rel:e})", sol.vol);
    }
    assert!(IV_REFS.len() > 100);
    println!("worst relative volatility error over {} cases: {worst:e}", IV_REFS.len());
}
"""
)


open(OUT, "w", encoding="utf-8").write("\n".join(lines))
print(len(rows), "reference points written to", OUT)
